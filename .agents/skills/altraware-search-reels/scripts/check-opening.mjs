import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {searchAt,validateOpening} from './search-opening.mjs';
const file=process.argv[2]||new URL('../examples/opening.plan.json',import.meta.url);
const p=validateOpening(JSON.parse(await readFile(file,'utf8'))),t=p.beats;
assert.equal(searchAt(p,0).query,'');
assert.equal(searchAt(p,t.typed).query,p.query);
assert.equal(searchAt(p,t.submit).phase,'waiting');
assert(!searchAt(p,t.ready-1).canShowResult);
assert.equal(searchAt(p,t.ready).phase,'result');
assert.equal(searchAt(p,t.hover).phase,'hover');
assert(searchAt(p,t.click).pressed);
assert.equal(searchAt(p,t.open).phase,'open');
const checkFrames=[0,t.typing,t.typed,t.submit,t.ready-1,t.ready,t.hover,t.click,t.open,t.end-1];
const sequential=Object.fromEntries(checkFrames.map(f=>[f,searchAt(p,f)]));
for(const f of checkFrames.slice().reverse())assert.deepEqual(searchAt(p,f),sequential[f]);
assert.throws(()=>validateOpening({...p,domain:'real-business.test'}));
assert.throws(()=>validateOpening({...p,beats:{...t,click:t.submit-1}}));
console.log(`${t.end} frames · type → send → sample link → click → open. No live returns.`);

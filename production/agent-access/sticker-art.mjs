const xy=([x,y])=>`${x.toFixed(2)} ${y.toFixed(2)}`;
const midpoint=(a,b)=>[(a[0]+b[0])/2,(a[1]+b[1])/2];
function draw(points,closed,offset){
  const sh=points.map(([x,y,hard],j)=>[x+.49*Math.sin(x*.35+y*.42+j*2.3+offset),y+.49*Math.cos(x*.24-y*.19+j*2.7+offset),hard]);
  const start=closed?midpoint(sh.at(-1),sh[0]):sh[0];
  const tokens=[`M${xy(start)}`];
  for(let j=closed?0:1;j<sh.length;j++){
    const a=sh[j];
    if(j===sh.length-1&&!closed){tokens.push(`L${xy(a)}`);break;}
    const b=midpoint(a,sh[(j+1)%sh.length]);
    tokens.push(a[2]?`L${xy(a)}L${xy(b)}`:`Q${xy(a)} ${xy(b)}`);
  }
  return tokens.join(' ')+(closed?' Z':'');
}
